#!/usr/bin/env node
/**
 * Kafka token build — zero dependencies.
 *
 *   tokens/primitives.json ┐
 *   tokens/semantic.json   ├─▶ src/styles/tokens.css   CSS custom properties (--kafka-*), aliases kept as var()
 *   tokens/components.json ┘   src/tokens.ts           Fully resolved values for JS
 *                              tokens/dist/tokens.json Flat, resolved — for Figma and other platforms
 *                              docs/tokens.md          Human-readable reference
 *
 * Format: W3C Design Tokens ($value / $type / $description). Aliases use {path.to.token}.
 * Dark values live in $extensions["kafka.modes"].dark. Same architecture as Pance.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const read = (f) => JSON.parse(readFileSync(resolve(root, f), 'utf8'))
const write = (f, s) => {
  const p = resolve(root, f)
  mkdirSync(dirname(p), { recursive: true })
  writeFileSync(p, s)
  console.log('  ✓', f)
}

const TIERS = ['primitives', 'semantic', 'components']
const tokens = new Map()
function walk(node, path, inheritedType, tier) {
  const type = node.$type ?? inheritedType
  if ('$value' in node) {
    const key = path.join('.')
    if (tokens.has(key)) throw new Error(`Duplicate token "${key}" (${tokens.get(key).tier} and ${tier})`)
    tokens.set(key, { path, value: node.$value, type, tier, description: node.$description, dark: node.$extensions?.['kafka.modes']?.dark, deprecated: node.$extensions?.['kafka.deprecated'] })
    return
  }
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('$') || typeof v !== 'object' || v === null) continue
    walk(v, [...path, k], type, tier)
  }
}
for (const t of TIERS) walk(read(`tokens/${t}.json`), [], undefined, t)

const REF = /^\{([^}]+)\}$/
const REF_G = /\{([^}]+)\}/g
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()
const cssName = (path) => `--kafka-${kebab(Array.isArray(path) ? path.join('-') : path.replace(/\./g, '-'))}`
const target = (ref, from) => {
  const t = tokens.get(ref)
  if (!t) throw new Error(`Unresolved alias {${ref}} in ${from}`)
  return t
}
function resolveValue(value, from, seen = new Set()) {
  if (typeof value === 'string') {
    const m = value.match(REF)
    if (m) {
      if (seen.has(m[1])) throw new Error(`Circular alias at ${from}`)
      return resolveValue(target(m[1], from).value, m[1], new Set([...seen, m[1]]))
    }
    return value.replace(REF_G, (_, r) => String(resolveValue(`{${r}}`, from, seen)))
  }
  if (Array.isArray(value)) return value.map((v) => resolveValue(v, from, seen))
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, resolveValue(v, from, seen)]))
  return value
}
const finalType = (tok) => {
  const m = typeof tok.value === 'string' && tok.value.match(REF)
  return m ? finalType(target(m[1], tok.path.join('.'))) : tok.type
}
for (const [key, tok] of tokens) if (tok.deprecated) console.warn(`  ⚠ ${key} is deprecated: ${tok.deprecated}`)
// Fail early on any dangling alias, including dark ones
for (const [key, tok] of tokens) {
  resolveValue(tok.value, key)
  if (tok.dark !== undefined) resolveValue(tok.dark, key)
}

const cssRef = (v) => (typeof v === 'string' ? v.replace(REF_G, (_, r) => `var(${cssName(r)})`) : v)
const fontStack = (arr) => arr.map((f) => (/\s/.test(f) && !/^ui-|^system-ui$/.test(f) ? `'${f}'` : f)).join(', ')
function toCss(tok) {
  const { value, type } = tok
  if (typeof value === 'string' && REF.test(value)) return cssRef(value)
  if (type === 'fontFamily') return Array.isArray(value) ? fontStack(value) : value
  if (type === 'shadow') return `${cssRef(value.offsetX)} ${cssRef(value.offsetY)} ${cssRef(value.blur)} ${cssRef(value.spread)} ${cssRef(value.color)}`
  if (type === 'gradient') return `linear-gradient(${value.angle}, ${value.stops.map((s) => `${cssRef(s.color)} ${s.position}`).join(', ')})`
  return cssRef(String(value))
}
const TYPO_PARTS = { fontFamily: 'font-family', fontSize: 'font-size', fontWeight: 'font-weight', fontStyle: 'font-style', lineHeight: 'line-height', letterSpacing: 'letter-spacing' }
// A typography token may alias another one; find the composite that actually holds the parts.
const typoSource = (tok) => {
  const m = typeof tok.value === 'string' && tok.value.match(REF)
  return m ? typoSource(target(m[1], tok.path.join('.'))) : tok
}

const header = (what) => `/* ${what}\n   AUTO-GENERATED by scripts/build-tokens.mjs from tokens/*.json — do not edit by hand. */\n`
let css = header('Kafka design tokens — CSS custom properties')
for (const tier of TIERS) {
  css += `\n/* ── ${tier} ${'─'.repeat(60 - tier.length)} */\n:root {\n`
  for (const tok of tokens.values()) {
    if (tok.tier !== tier) continue
    const name = cssName(tok.path)
    if (finalType(tok) === 'typography') {
      const m = typeof tok.value === 'string' && tok.value.match(REF)
      const src = typoSource(tok).value
      for (const [k, part] of Object.entries(TYPO_PARTS)) {
        if (src[k] === undefined) continue
        css += `  ${name}-${part}: ${m ? `var(${cssName(m[1])}-${part})` : cssRef(String(k === 'fontFamily' ? toCss({ value: tok.value[k], type: 'fontFamily' }) : tok.value[k]))};\n`
      }
      continue
    }
    css += `  ${name}: ${toCss(tok)};\n`
  }
  css += '}\n'
}
const darkToks = [...tokens.values()].filter((t) => t.dark !== undefined)
const darkBlock = darkToks.map((t) => `  ${cssName(t.path)}: ${cssRef(t.dark)};`).join('\n')
css += `\n/* ── dark: follows the system unless data-theme="light"; force with data-theme="dark" ── */\n@media (prefers-color-scheme: dark) {\n  :root:not([data-theme='light']) {\n${darkBlock.replace(/^/gm, '  ')}\n  }\n}\n:root[data-theme='dark'] {\n${darkBlock}\n}\n`
write('src/styles/tokens.css', css)

// ── themes: tokens/themes/<name>.json → src/styles/themes/<name>.css ──
// A theme overrides existing semantic or component tokens (same path) and may add its own tokens under "<name>.".
// Custom properties that use var() are resolved where they are declared, so a scope only changes what the theme
// touches AND everything that depends on it: the compiler redeclares those dependents inside the scope.
const themeDir = resolve(root, 'tokens/themes')
const themeNames = existsSync(themeDir) ? readdirSync(themeDir).filter((f) => f.endsWith('.json')).map((f) => f.replace(/\.json$/, '')).sort() : []
for (const name of themeNames) {
  const own = new Map()
  const walkTheme = (node, path, inheritedType) => {
    const type = node.$type ?? inheritedType
    if ('$value' in node) { own.set(path.join('.'), { path, value: node.$value, type, dark: node.$extensions?.['kafka.modes']?.dark }); return }
    for (const [k, v] of Object.entries(node)) if (!k.startsWith('$') && typeof v === 'object' && v !== null) walkTheme(v, [...path, k], type)
  }
  walkTheme(read(`tokens/themes/${name}.json`), [], undefined)
  const overridden = [], created = []
  for (const [key, t] of own) {
    if (key.startsWith(`${name}.`)) { created.push(key); continue }
    const base = tokens.get(key)
    if (!base) throw new Error(`Theme ${name}: "${key}" does not exist in the base tokens (new tokens go under "${name}.")`)
    if (base.tier === 'primitives') throw new Error(`Theme ${name}: "${key}" is a primitive; a theme overrides semantic or component tokens`)
    if (finalType(base) === 'typography') throw new Error(`Theme ${name}: "${key}" is a typography token; themes do not override typography`)
    overridden.push(key)
  }
  const known = (r) => tokens.has(r) || own.has(r)
  for (const [key, t] of own) for (const v of [t.value, t.dark]) for (const m of typeof v === 'string' ? v.matchAll(REF_G) : []) if (!known(m[1])) throw new Error(`Theme ${name}: "${key}" points at unknown token {${m[1]}}`)
  // dependents: base tokens that reach an overridden token through their light or dark value
  const reaches = (key, seen = new Set()) => {
    if (overridden.includes(key)) return true
    if (seen.has(key)) return false
    seen.add(key)
    const t = tokens.get(key)
    if (!t) return false
    return [t.value, t.dark].some((v) => typeof v === 'string' && [...v.matchAll(REF_G)].some((m) => reaches(m[1], seen)))
  }
  const dependents = [...tokens.keys()].filter((k) => !overridden.includes(k) && reaches(k))
  const lines = (keys, pick) => keys.map((k) => { const v = pick(k); return v === undefined ? null : `  ${cssName(k)}: ${v};` }).filter(Boolean).join('\n')
  const light = (k) => (own.has(k) ? toCss({ value: own.get(k).value, type: own.get(k).type ?? tokens.get(k)?.type }) : toCss(tokens.get(k)))
  // dark: the theme's own dark value, else the base's dark value; tokens with neither are the same in both modes
  const dark = (k) => {
    const d = own.has(k) && own.get(k).dark !== undefined ? own.get(k).dark : tokens.get(k)?.dark
    return d === undefined ? undefined : cssRef(d)
  }
  const keys = [...overridden, ...created, ...dependents]
  const scope = `[data-kafka-theme='${name}']`
  const darkBody = lines(keys, dark)
  let themeCss = header(`Kafka theme "${name}" — scope [data-kafka-theme="${name}"]`)
  themeCss += `${scope} {\n${lines(keys, light)}\n}\n`
  if (darkBody) {
    const sys = `:root:not([data-theme='light']) ${scope}, :root:not([data-theme='light'])${scope}`
    const forced = `:root[data-theme='dark'] ${scope}, :root[data-theme='dark']${scope}`
    themeCss += `\n/* dark: same rule as the base tokens */\n@media (prefers-color-scheme: dark) {\n  ${sys} {\n${darkBody.replace(/^/gm, '  ')}\n  }\n}\n${forced} {\n${darkBody}\n}\n`
  }
  write(`src/styles/themes/${name}.css`, themeCss)
}

// ── typography.css: one class per typography token (e.g. .kafka-type-reading-body, .kafka-type-button-type) ──
let typo = header('Kafka typography classes — one per typography token')
for (const tok of tokens.values()) {
  if (finalType(tok) !== 'typography') continue
  const name = cssName(tok.path)
  const parts = Object.entries(TYPO_PARTS).filter(([k]) => typoSource(tok).value[k] !== undefined)
  typo += `.kafka-type-${tok.path.map(kebab).join('-')} {\n${parts.map(([, part]) => `  ${part}: var(${name}-${part});`).join('\n')}\n}\n`
}
write('src/styles/typography.css', typo)

// ── theme.css: Tailwind v4 theme. Default palettes, sizes, radii and shadows are switched off on purpose,
//    so the only utilities that exist are the ones backed by a Kafka token. ──
const v = (p) => `var(${cssName(p)})`
const px = (ref) => String(resolveValue(`{${ref}}`, ref)).replace(/^([\d.]+)rem$/, (_, n) => `${+n * 16}px`)
const COLOR_UTILS = {
  'color.bg.page': 'page', 'color.bg.surface': 'surface', 'color.bg.sunken': 'sunken', 'color.bg.inverse': 'inverse', 'color.bg.brand': 'brand',
  'color.fg.default': 'ink', 'color.fg.soft': 'ink-soft', 'color.fg.muted': 'ink-muted', 'color.fg.brand': 'ink-brand', 'color.fg.link': 'link', 'color.fg.inverse': 'ink-inverse', 'color.fg.on-brand': 'on-brand',
  'color.border.default': 'line', 'color.border.strong': 'line-strong', 'color.border.focus': 'line-focus', 'color.border.brand': 'line-brand',
}
const fam = ['reading', 'ui', 'mono'].map((f) => `  --font-${f}: ${v(`fontFamily.${f}`)};`)
const sizes = [...tokens.keys()].filter((k) => /^fontSize\.\d+$/.test(k)).map((k) => `  --text-${k.split('.')[1]}: ${v(k)};`)
const weights = ['regular', 'medium', 'semibold', 'bold'].map((w) => `  --font-weight-${w}: ${v(`fontWeight.${w}`)};`)
const leadings = ['heading', 'ui', 'reading'].map((l) => `  --leading-${l}: ${v(`lineHeight.${l}`)};`)
const tracks = ['tight', 'normal', 'wide', 'wider'].map((t) => `  --tracking-${t}: ${v(`letterSpacing.${t}`)};`)
const radii = [...[4, 8, 12, 16, 20].map((r) => `  --radius-${r}: ${v(`radius.${r}`)};`), ...['control', 'card', 'media', 'pill'].map((r) => `  --radius-${r}: ${v(`radius.${r}`)};`), `  --radius-full: ${v('radius.full')};`]
const shadows = ['sm', 'md', 'lg', 'glow'].map((x) => `  --shadow-${x}: ${v(`shadow.${x}`)};`)
const bps = ['sm', 'md', 'lg', 'xl'].map((b) => `  --breakpoint-${b}: ${px(`breakpoint.${b}`)};`)
const colors = Object.entries(COLOR_UTILS).map(([p, u]) => `  --color-${u}: ${v(p)};`)
const theme = `${header('Kafka → Tailwind v4 theme')}@theme {
  /* Switch off Tailwind's defaults: only token-backed utilities exist. */
  --color-*: initial;
  --text-*: initial;
  --font-weight-*: initial;
  --leading-*: initial;
  --tracking-*: initial;
  --radius-*: initial;
  --shadow-*: initial;
  --drop-shadow-*: initial;
  --breakpoint-*: initial;

  --color-transparent: transparent;
  --color-current: currentColor;
${colors.join('\n')}

${fam.join('\n')}
${sizes.join('\n')}
${weights.join('\n')}
${leadings.join('\n')}
${tracks.join('\n')}

${radii.join('\n')}
${shadows.join('\n')}
${bps.join('\n')}
}
`
write('src/styles/theme.css', theme)

const resolved = {}
for (const [key, tok] of tokens) {
  let v = resolveValue(tok.value, key)
  if (finalType(tok) === 'fontFamily' && Array.isArray(v)) v = fontStack(v)
  resolved[key] = v
}
const nested = {}
for (const [key, v] of Object.entries(resolved)) {
  const parts = key.split('.')
  let o = nested
  parts.slice(0, -1).forEach((p) => (o = o[p] ??= {}))
  o[parts.at(-1)] = v
}
write('src/tokens.ts', `${header('Kafka design tokens — resolved values for JavaScript').replace('/*', '/**')}\nexport const tokens = ${JSON.stringify(nested, null, 2)} as const\n\nexport type KafkaTokens = typeof tokens\nexport default tokens\n`)
write('tokens/dist/tokens.json', JSON.stringify(resolved, null, 2) + '\n')

const esc = (s) => String(s).replace(/\|/g, '\\|')
const INTRO = {
  primitives: 'Raw values. Only referenced by semantic and component tokens.',
  semantic: 'Purpose-based aliases (surface, text, reading, typography roles). Use these in product code.',
  components: 'Per-component decisions, aliased to semantic or primitive tokens.',
}
let md = `<!-- AUTO-GENERATED by scripts/build-tokens.mjs — do not edit by hand. -->\n# Token reference\n\n${tokens.size} tokens across three tiers. Source of truth: [\`/tokens\`](../tokens). CSS variable = \`--kafka-\` + the path in kebab-case.\n\n`
for (const tier of TIERS) {
  md += `## ${tier[0].toUpperCase() + tier.slice(1)}\n\n${INTRO[tier]}\n\n| Token | Resolved | Dark | Notes |\n|---|---|---|---|\n`
  for (const tok of tokens.values()) {
    if (tok.tier !== tier) continue
    const key = tok.path.join('.')
    const r = resolved[key]
    const dk = tok.dark !== undefined ? resolveValue(tok.dark, key) : ''
    md += `| \`${key}\` | ${esc(typeof r === 'object' ? JSON.stringify(r) : r)} | ${esc(dk)} | ${esc([tok.deprecated ? `**Deprecated:** ${tok.deprecated}` : '', tok.description ?? ''].filter(Boolean).join(' '))} |\n`
  }
  md += '\n'
}
write('docs/tokens.md', md)
console.log(`\n  ${tokens.size} tokens (${TIERS.map((t) => `${t}: ${[...tokens.values()].filter((x) => x.tier === t).length}`).join(' · ')})`)
