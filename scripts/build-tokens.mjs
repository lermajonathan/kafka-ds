#!/usr/bin/env node
/**
 * Kafka token build — zero dependencies.
 *
 *   tokens/primitives.json ┐
 *   tokens/semantic.json   ├─▶ src/styles/tokens.css   CSS custom properties (--kafka-*), aliases kept as var()
 *   tokens/components.json ┘   src/tokens.ts           Fully resolved values for JS
 *                              tokens/dist/tokens.json Flat, resolved — for Figma and other platforms
 *                              docs/tokens.md          Human-readable reference
 *
 * Format: W3C Design Tokens ($value / $type / $description). Aliases use {path.to.token}.
 * Dark values live in $extensions["kafka.modes"].dark. Same architecture as Pance.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const read = (f) => JSON.parse(readFileSync(resolve(root, f), 'utf8'))
const write = (f, s) => {
  const p = resolve(root, f)
  mkdirSync(dirname(p), { recursive: true })
  writeFileSync(p, s)
  console.log('  ✓', f)
}

const TIERS = ['primitives', 'semantic', 'components']
const tokens = new Map()
function walk(node, path, inheritedType, tier) {
  const type = node.$type ?? inheritedType
  if ('$value' in node) {
    const key = path.join('.')
    if (tokens.has(key)) throw new Error(`Duplicate token "${key}" (${tokens.get(key).tier} and ${tier})`)
    tokens.set(key, { path, value: node.$value, type, tier, description: node.$description, dark: node.$extensions?.['kafka.modes']?.dark })
    return
  }
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('$') || typeof v !== 'object' || v === null) continue
    walk(v, [...path, k], type, tier)
  }
}
for (const t of TIERS) walk(read(`tokens/${t}.json`), [], undefined, t)

const REF = /^\{([^}]+)\}$/
const REF_G = /\{([^}]+)\}/g
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()
const cssName = (path) => `--kafka-${kebab(Array.isArray(path) ? path.join('-') : path.replace(/\./g, '-'))}`
const target = (ref, from) => {
  const t = tokens.get(ref)
  if (!t) throw new Error(`Unresolved alias {${ref}} in ${from}`)
  return t
}
function resolveValue(value, from, seen = new Set()) {
  if (typeof value === 'string') {
    const m = value.match(REF)
    if (m) {
      if (seen.has(m[1])) throw new Error(`Circular alias at ${from}`)
      return resolveValue(target(m[1], from).value, m[1], new Set([...seen, m[1]]))
    }
    return value.replace(REF_G, (_, r) => String(resolveValue(`{${r}}`, from, seen)))
  }
  if (Array.isArray(value)) return value.map((v) => resolveValue(v, from, seen))
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, resolveValue(v, from, seen)]))
  return value
}
const finalType = (tok) => {
  const m = typeof tok.value === 'string' && tok.value.match(REF)
  return m ? finalType(target(m[1], tok.path.join('.'))) : tok.type
}
// Fail early on any dangling alias, including dark ones
for (const [key, tok] of tokens) {
  resolveValue(tok.value, key)
  if (tok.dark !== undefined) resolveValue(tok.dark, key)
}

const cssRef = (v) => (typeof v === 'string' ? v.replace(REF_G, (_, r) => `var(${cssName(r)})`) : v)
const fontStack = (arr) => arr.map((f) => (/\s/.test(f) && !/^ui-|^system-ui$/.test(f) ? `'${f}'` : f)).join(', ')
function toCss(tok) {
  const { value, type } = tok
  if (typeof value === 'string' && REF.test(value)) return cssRef(value)
  if (type === 'fontFamily') return Array.isArray(value) ? fontStack(value) : value
  return cssRef(String(value))
}
const TYPO_PARTS = { fontFamily: 'font-family', fontSize: 'font-size', fontWeight: 'font-weight', lineHeight: 'line-height', letterSpacing: 'letter-spacing' }

const header = (what) => `/* ${what}\n   AUTO-GENERATED by scripts/build-tokens.mjs from tokens/*.json — do not edit by hand. */\n`
let css = header('Kafka design tokens — CSS custom properties')
for (const tier of TIERS) {
  css += `\n/* ── ${tier} ${'─'.repeat(60 - tier.length)} */\n:root {\n`
  for (const tok of tokens.values()) {
    if (tok.tier !== tier) continue
    const name = cssName(tok.path)
    if (finalType(tok) === 'typography') {
      const m = typeof tok.value === 'string' && tok.value.match(REF)
      for (const [k, part] of Object.entries(TYPO_PARTS)) {
        css += `  ${name}-${part}: ${m ? `var(${cssName(m[1])}-${part})` : cssRef(String(k === 'fontFamily' ? toCss({ value: tok.value[k], type: 'fontFamily' }) : tok.value[k]))};\n`
      }
      continue
    }
    css += `  ${name}: ${toCss(tok)};\n`
  }
  css += '}\n'
}
const darkToks = [...tokens.values()].filter((t) => t.dark !== undefined)
const darkBlock = darkToks.map((t) => `  ${cssName(t.path)}: ${cssRef(t.dark)};`).join('\n')
css += `\n/* ── dark: follows the system unless data-theme="light"; force with data-theme="dark" ── */\n@media (prefers-color-scheme: dark) {\n  :root:not([data-theme='light']) {\n${darkBlock.replace(/^/gm, '  ')}\n  }\n}\n:root[data-theme='dark'] {\n${darkBlock}\n}\n`
write('src/styles/tokens.css', css)

const resolved = {}
for (const [key, tok] of tokens) {
  let v = resolveValue(tok.value, key)
  if (finalType(tok) === 'fontFamily' && Array.isArray(v)) v = fontStack(v)
  resolved[key] = v
}
const nested = {}
for (const [key, v] of Object.entries(resolved)) {
  const parts = key.split('.')
  let o = nested
  parts.slice(0, -1).forEach((p) => (o = o[p] ??= {}))
  o[parts.at(-1)] = v
}
write('src/tokens.ts', `${header('Kafka design tokens — resolved values for JavaScript').replace('/*', '/**')}\nexport const tokens = ${JSON.stringify(nested, null, 2)} as const\n\nexport type KafkaTokens = typeof tokens\nexport default tokens\n`)
write('tokens/dist/tokens.json', JSON.stringify(resolved, null, 2) + '\n')

const esc = (s) => String(s).replace(/\|/g, '\\|')
const INTRO = {
  primitives: 'Raw values. Only referenced by semantic and component tokens.',
  semantic: 'Purpose-based aliases (surface, text, reading, typography roles). Use these in product code.',
  components: 'Per-component decisions, aliased to semantic or primitive tokens.',
}
let md = `<!-- AUTO-GENERATED by scripts/build-tokens.mjs — do not edit by hand. -->\n# Token reference\n\n${tokens.size} tokens across three tiers. Source of truth: [\`/tokens\`](../tokens). CSS variable = \`--kafka-\` + the path in kebab-case.\n\n`
for (const tier of TIERS) {
  md += `## ${tier[0].toUpperCase() + tier.slice(1)}\n\n${INTRO[tier]}\n\n| Token | Resolved | Dark | Notes |\n|---|---|---|---|\n`
  for (const tok of tokens.values()) {
    if (tok.tier !== tier) continue
    const key = tok.path.join('.')
    const r = resolved[key]
    const dk = tok.dark !== undefined ? resolveValue(tok.dark, key) : ''
    md += `| \`${key}\` | ${esc(typeof r === 'object' ? JSON.stringify(r) : r)} | ${esc(dk)} | ${esc(tok.description ?? '')} |\n`
  }
  md += '\n'
}
write('docs/tokens.md', md)
console.log(`\n  ${tokens.size} tokens (${TIERS.map((t) => `${t}: ${[...tokens.values()].filter((x) => x.tier === t).length}`).join(' · ')})`)
