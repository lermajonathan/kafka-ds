#!/usr/bin/env node
/**
 * Generates one documentation page per component (docs/components/<id>.md) plus an index.
 *   - props, defaults and descriptions come from the TypeScript source (so they cannot drift)
 *   - examples come from examples/<id>.tsx, printed as the JSX that runs in the playground
 *   - tokens come from tokens/components.json
 *   - the human guidance (when to use, accessibility, content) lives in scripts/docs/<id>.mjs
 * `--check` regenerates in memory and fails if the committed pages differ (used in CI).
 */
import fs from 'node:fs'
import path from 'node:path'
import ts from 'typescript'

const root = path.resolve(import.meta.dirname, '..')
const CHECK = process.argv.includes('--check')
const { registry } = await import('tsx/esm/api').then(({ tsImport }) => tsImport('../examples/index.ts', import.meta.url))

const componentTokens = JSON.parse(fs.readFileSync(path.join(root, 'tokens/components.json'), 'utf8'))
const flat = (node, p = []) => Object.entries(node).flatMap(([k, v]) => (k.startsWith('$') ? [] : '$value' in v ? [[[...p, k].join('.'), v]] : flat(v, [...p, k])))

const parse = (file) => {
  const text = fs.readFileSync(path.join(root, file), 'utf8')
  return { text, sf: ts.createSourceFile(file, text, ts.ScriptTarget.ES2022, true, file.endsWith('x') ? ts.ScriptKind.TSX : ts.ScriptKind.TS) }
}
const jsdoc = (node) => ts.getJSDocCommentsAndTags(node).filter(ts.isJSDoc).map((d) => ts.getTextOfJSDocComment(d.comment) ?? '').join(' ').replace(/\s+/g, ' ').trim()
const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ')

/** Props of `<Name>Props`, with defaults read from the destructured parameters of the component function. */
function propsOf(file, name) {
  const { sf } = parse(file)
  let iface, fn
  sf.forEachChild((n) => {
    if ((ts.isInterfaceDeclaration(n) || ts.isTypeAliasDeclaration(n)) && n.name.text === `${name}Props`) iface = n
    if (ts.isFunctionDeclaration(n) && n.name?.text === name) fn = n
  })
  if (!iface) throw new Error(`${file}: no ${name}Props`)
  const defaults = {}
  const param = fn?.parameters[0]
  if (param && ts.isObjectBindingPattern(param.name)) for (const el of param.name.elements) if (el.initializer && ts.isIdentifier(el.name)) defaults[el.name.text] = el.initializer.getText(sf)
  const members = ts.isInterfaceDeclaration(iface) ? iface.members : iface.type.members ?? []
  const own = [...members].filter(ts.isPropertySignature).map((m) => ({ name: m.name.getText(sf), type: m.type.getText(sf), optional: !!m.questionToken, def: defaults[m.name.getText(sf)], doc: jsdoc(m) }))
  const extendsText = ts.isInterfaceDeclaration(iface) ? (iface.heritageClauses ?? []).flatMap((h) => h.types.map((t) => t.getText(sf))) : []
  return { own, extendsText, doc: jsdoc(iface), fnDoc: fn ? jsdoc(fn) : '' }
}

/** The JSX each example renders, dedented. */
function exampleSource(id, exampleId) {
  const { sf } = parse(`examples/${id}.tsx`)
  let out
  const visit = (n) => {
    if (ts.isObjectLiteralExpression(n)) {
      const props = Object.fromEntries(n.properties.filter(ts.isPropertyAssignment).map((p) => [p.name.getText(sf), p.initializer]))
      if (props.id && ts.isStringLiteral(props.id) && props.id.text === exampleId && props.render && ts.isArrowFunction(props.render)) {
        let body = props.render.body
        if (ts.isParenthesizedExpression(body)) body = body.expression
        const lines = body.getText(sf).split('\n')
        const indent = Math.min(...lines.slice(1).filter((l) => l.trim()).map((l) => l.match(/^ */)[0].length), Infinity)
        out = [lines[0], ...lines.slice(1).map((l) => l.slice(Number.isFinite(indent) ? indent : 0))].join('\n')
      }
    }
    ts.forEachChild(n, visit)
  }
  visit(sf)
  if (!out) throw new Error(`examples/${id}.tsx: no example "${exampleId}"`)
  return out
}

const pages = {}
const index = {}
for (const [id, entry] of Object.entries(registry)) {
  const g = (await import(`./docs/${id}.mjs`)).default
  const p = propsOf(`src/components/${entry.file}`, entry.name)
  const tokens = flat(componentTokens).filter(([k]) => k.split('.')[0] === id)
  let md = `<!-- AUTO-GENERATED by scripts/build-docs.mjs — props from src/components/${entry.file}, examples from examples/${id}.tsx. Do not edit by hand. -->\n`
  md += `# ${entry.name}\n\n${g.summary}\n\n\`\`\`tsx\nimport { ${entry.name} } from '@kafka/react'\n\`\`\`\n\n`
  md += `## When to use it\n\n${g.use.map((x) => `- ${x}`).join('\n')}\n\n## When not to\n\n${g.avoid.map((x) => `- ${x}`).join('\n')}\n\n`
  md += `## Examples\n\n`
  for (const ex of entry.examples) md += `### ${ex.title}\n\n${ex.description ? `${ex.description}\n\n` : ''}\`\`\`tsx\n${exampleSource(id, ex.id)}\n\`\`\`\n\n`
  md += `## Props\n\n| Prop | Type | Default | Description |\n|---|---|---|---|\n`
  for (const m of p.own) md += `| \`${m.name}\`${m.optional ? '' : ' (required)'} | \`${esc(m.type)}\` | ${m.def ? `\`${esc(m.def)}\`` : ''} | ${esc(m.doc)} |\n`
  if (p.extendsText.length) md += `| …rest | \`${esc(p.extendsText.map((t) => t.replace(/^Omit<(.*?),.*$/, '$1')).join(', '))}\` | | Everything else is passed to the underlying element. |\n`
  md += `\n## Accessibility\n\n${g.accessibility.map((x) => `- ${x}`).join('\n')}\n\n## Content\n\n${g.content.map((x) => `- ${x}`).join('\n')}\n\n`
  md += `## Tokens\n\nComponent tokens, all aliasing semantic tokens (see [tokens.md](../tokens.md)). CSS variable = \`--kafka-\` + the path in kebab-case.\n\n| Token | Value |\n|---|---|\n`
  for (const [k, v] of tokens) md += `| \`${k}\` | \`${esc(typeof v.$value === 'string' ? v.$value : JSON.stringify(v.$value))}\` |\n`
  if (g.related?.length) md += `\n## Related\n\n${g.related.map((r) => `- \`${r}\``).join('\n')}\n`
  pages[`docs/components/${id}.md`] = md
  ;(index[g.category] ??= []).push([id, entry.name, g.summary.split('. ')[0].replace(/\.$/, '') + '.'])
}
let readme = `<!-- AUTO-GENERATED by scripts/build-docs.mjs — do not edit by hand. -->\n# Components\n\n${Object.keys(registry).length} component${Object.keys(registry).length === 1 ? '' : 's'}, one page each: when to use it, runnable examples, props (generated from the TypeScript source, so they cannot drift), accessibility, content guidance and tokens. The roadmap to the full set is in [roadmap.md](../roadmap.md).\n\n`
for (const [cat, rows] of Object.entries(index)) readme += `## ${cat}\n\n| Component | Use it for |\n|---|---|\n${rows.map(([id, n, s]) => `| [\`${n}\`](${id}.md) | ${s} |`).join('\n')}\n\n`
pages['docs/components/README.md'] = readme

let drift = 0
for (const [file, content] of Object.entries(pages)) {
  const abs = path.join(root, file)
  if (CHECK) { if (!fs.existsSync(abs) || fs.readFileSync(abs, 'utf8') !== content) { drift++; console.log(`  ✗ ${file} is out of date`) } }
  else { fs.mkdirSync(path.dirname(abs), { recursive: true }); fs.writeFileSync(abs, content); console.log('  ✓', file) }
}
if (CHECK) { if (drift) { console.log(`\n✗ ${drift} page(s) out of date. Run \`pnpm docs\` and commit.`); process.exit(1) } console.log(`✓ Documentation is up to date (${Object.keys(pages).length} pages)`) }
